// Impacto esperado por faixa de aquecimento (IPCC AR6, linguagem simplificada), nos dois idiomas.
// A temperatura do app é em relação a 1951–1980; a era pré-industrial é ~0,3 °C mais fria.
EJ.impactFor = function (t) {
  const pre = t + 0.3;                       // aquecimento aproximado desde a era pré-industrial
  const en = EJ.i18n && EJ.i18n.lang === 'en';
  if (pre < 1.6) return en ? 'Heat waves and extreme rainfall become more frequent, and many coral reefs suffer repeated bleaching.'
                           : 'Ondas de calor e chuvas extremas ficam mais frequentes, e muitos recifes de coral sofrem branqueamento repetido.';
  if (pre < 2.1) return en ? 'Close to two degrees, most coral reefs may disappear, and droughts and floods become much more common.'
                           : 'Perto de dois graus, a maior parte dos recifes de coral pode desaparecer, e secas e enchentes ficam bem mais comuns.';
  if (pre < 3.1) return en ? 'Close to three degrees, mountain glaciers shrink a lot, harvests in tropical regions fall and extreme heat becomes routine in many places.'
                           : 'Perto de três graus, geleiras de montanha encolhem muito, colheitas em regiões tropicais caem e o calor extremo vira rotina em muitos lugares.';
  return en ? 'Above three degrees, heat can become dangerous to health for much of the year in tropical regions, and the sea threatens coastal cities all over the world.'
            : 'Acima de três graus, o calor pode ficar perigoso para a saúde em boa parte do ano nas regiões tropicais, e o mar ameaça cidades costeiras no mundo todo.';
};

